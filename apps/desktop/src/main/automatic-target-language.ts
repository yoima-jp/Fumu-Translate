import type { SettingsSnapshot } from '../shared/settings-contracts';

// 自動翻訳の翻訳先は「原文が母国語なら対訳先、それ以外なら母国語」で決まる。
// 判定が機械的に行える原文はこのモジュールで確定し、Providerの言語判定に委ねない。
// Providerが原文言語を取り違えると、ルーティング規則どおりでも逆方向の訳が出るためである
// (例: 中国語を日本語と判定すると、中国語の原文が英語へ訳される)。
// 判定できない原文だけをnullで返し、Providerのルーティングへ委ねる。
//
// 母国語が日本語以外の利用者では、原文がその母国語かどうかを機械的に判定できないため
// 何も確定しない。日本語話者はかなの有無という決定的な証拠を持てるので、ここでしか
// 自動判定を確定させない。

/** かな。日本語の文は漢字だけで書かれないため、方向判定の決定的な証拠になる。 */
const JAPANESE_KANA = /[\u3040-\u30ff\uff66-\uff9f]/u;

/** CJK統合漢字。これを含まない原文は日本語でも中国語でもない。 */
const CJK_UNIFIED_IDEOGRAPH = /[\u3400-\u9fff]/u;

/**
 * 中国語にしか現れない文字。
 *
 * 漢字だけの原文(例: 互換性)は日本語とも中国語とも読めるため、かなやラテン文字のように
 * 機械的には判定できない。そこで「日本語では使わない字形」を中国語の積極的な証拠として
 * 扱い、証拠があるときだけ母国語(外国語の受け皿)へ固定する。
 *
 * 収録の基準は次の2つだけである。
 * - 簡体字の偏(訁→讠、釒→钅、糹→纟、飠→饣、見→见、貝→贝、門→门、馬→马、鳥→鸟、
 *   魚→鱼、車→车、頁→页)で作られた字。
 * - 現代日本語の新字体とは別字形の繁体字。
 *
 * 日本語でも使う字(例: 換・個・頭・導・層・師・庫・愛・無・有・区・点・灯・号・医・
 * 車・馬・鳥・魚・話・語・買・購・請)は入れない。誤判定すると日本語の漢字語がそのまま
 * 返る無意味な翻訳になるため、網羅よりも精度を優先する。
 *
 * 網羅は目的ではないが、中国語の文は通常この中のどれかを含むため、証拠として十分に働く。
 * どれも含まない短い原文(例: 「今天下雨」)はProviderの判定に委ねる。
 */
const CHINESE_ONLY_CHARACTERS: ReadonlySet<string> = new Set(
  [
    // 言偏(訁→讠)
    '计订认讨让训议记讲论设访证评识诉词译试话询该详语说请读课谁调谈谢谨谱赞',
    // 金偏(釒→钅)
    '钱铁银错钟钢铜铝铅铺锁钥针钉钩销锋锐镜锅',
    // 糸偏(糹→纟)
    '红级纪约纯纸线组细织终经结给络维绿缓编练绝统继续缠缘缩缝',
    // 食偏(飠→饣)
    '饭饮饿饱馆饼馒饺',
    // 見・貝・門・馬・鳥・魚・車・頁
    '见观规觉视览贝财责贵买贷贸费贴赚购赔赏赐账贺货门闭问间闻阅闲闹马驰驱驳驻驾骂骄骗骑鸟鸡鸣鸭鹅鱼鲜鲸轨转轮软轻载输辈辉辅页顶项顺须顾预题颗领频颜',
    // 王・阝
    '环现玛队阳阴际陆陈险',
    // その他の簡体字
    '长东电书单从无专业乐习亚产亲亿仅仓价伪传伟伤员团队图场块坚报择损换据摄权药雾册须帮师庆库归个们么儿头对为时务张欢难汉戏劝叹义举兴农优忆惊怀态变边达过运进远违连迟适选递这还邮郑释飞风龙龟齿龄脑网络站码删户币链卡收卖汤狗',
    // 日本語と字形が重ならない中国語だけの字
    '您你她它咱啥咋查很吗呢吧',
    // 現代日本語が使わない繁体字
    '們這說讓對單號從產專與雙數處夠盡歲帶應廣實發關檢驗據權觀樂藥醫錢點燈圖團麼兒邊',
  ].join(''),
);

/** 中国語の文に現れる字かどうか。1字でも見つかれば中国語の証拠として扱う。 */
function containsChineseOnlyCharacter(sourceText: string): boolean {
  for (const character of sourceText) {
    if (CHINESE_ONLY_CHARACTERS.has(character)) return true;
  }
  return false;
}

/**
 * Providerへ委ねずに翻訳先を確定できる場合だけ、その言語名を返す。
 * 判定できない場合はnullを返し、呼び出し側がProviderのルーティングを使えるようにする。
 */
export function automaticTargetLanguage(
  sourceText: string,
  settings: Pick<SettingsSnapshot, 'nativeLanguage' | 'otherLanguageTarget'>,
): string | null {
  if (settings.nativeLanguage !== 'Japanese') return null;

  // かながあれば原文は日本語(母国語)なので、対訳先へ訳す。
  if (JAPANESE_KANA.test(sourceText)) return settings.otherLanguageTarget;
  // 漢字を含まない原文は日本語ではない。母国語がそのまま受け皿になる。
  if (!CJK_UNIFIED_IDEOGRAPH.test(sourceText)) return 'Japanese';
  // 漢字だけでも、日本語に無い字形があれば中国語と判断して母国語へ訳す。
  if (containsChineseOnlyCharacter(sourceText)) return 'Japanese';
  // 証拠が無い場合は確定しない。短い日本語の漢字語を中国語と誤ると、原文がそのまま
  // 返る無意味な翻訳になるため、確証が無い限りどちらにも倒さない。
  return null;
}
